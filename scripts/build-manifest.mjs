import { writeFile } from 'node:fs/promises';
import manifest from '../dist/manifest.js';

// Paperclip cache-busts the manifest entry but not its transitive imports.
// Materialize data in a fresh build process so upgrades cannot reuse a stale
// config module cached by the long-running native host. No runtime dependency.
await writeFile(new URL('../dist/manifest.js', import.meta.url),
  `// Generated by scripts/build-manifest.mjs; edit src/manifest.ts.\nexport default ${JSON.stringify(manifest, null, 2)};\n`);
